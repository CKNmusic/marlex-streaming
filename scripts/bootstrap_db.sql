\set ON_ERROR_STOP on

BEGIN;

DROP TABLE IF EXISTS records CASCADE;

DROP TABLE IF EXISTS user_device_access CASCADE;

DROP TABLE IF EXISTS devices CASCADE;

DROP TABLE IF EXISTS marks CASCADE;

DROP TABLE IF EXISTS places CASCADE;

DROP TABLE IF EXISTS cities CASCADE;

DROP TABLE IF EXISTS procedures CASCADE;

DROP TABLE IF EXISTS protocols CASCADE;

DROP TABLE IF EXISTS users CASCADE;

DROP TABLE IF EXISTS app_settings CASCADE;

DROP TYPE IF EXISTS device_status CASCADE;

CREATE TABLE app_settings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    host VARCHAR(255) NOT NULL,
    recordings_dir VARCHAR(512) NOT NULL DEFAULT '/recordings',
    output_format VARCHAR(8) NOT NULL DEFAULT 'mkv',
    scan_start_in INTEGER NOT NULL DEFAULT 60,
    CONSTRAINT pk_app_settings_id PRIMARY KEY (id)
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR(255),
    username VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    is_superuser BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now (),
    CONSTRAINT pk_users_id PRIMARY KEY (id),
    CONSTRAINT uq_users_username UNIQUE (username)
);

CREATE INDEX ix_users_full_name ON users (full_name);

CREATE TABLE protocols (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(32) NOT NULL,
    port INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_protocols_id PRIMARY KEY (id),
    CONSTRAINT uq_protocols_name UNIQUE (name),
    CONSTRAINT uq_protocols_port UNIQUE (port),
    CONSTRAINT ck_protocols_port CHECK (port BETWEEN 1 AND 65535)
);

CREATE TABLE marks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now (),
    CONSTRAINT pk_marks_id PRIMARY KEY (id),
    CONSTRAINT uq_marks_name UNIQUE (name)
);

CREATE INDEX ix_marks_name ON marks (name);

CREATE TABLE procedures (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now (),
    CONSTRAINT pk_procedures_id PRIMARY KEY (id),
    CONSTRAINT uq_procedures_name UNIQUE (name)
);

CREATE INDEX ix_procedures_name ON procedures (name);

CREATE TABLE cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cities_id PRIMARY KEY (id),
    CONSTRAINT uq_cities_name_uf UNIQUE (name, uf)
);

CREATE INDEX ix_cities_name ON cities (name);

CREATE TABLE places (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    city_id INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_places_id PRIMARY KEY (id),
    CONSTRAINT fk_places_city_id FOREIGN KEY (city_id) REFERENCES cities (id) ON DELETE RESTRICT
);

CREATE INDEX ix_places_name ON places (name);

CREATE INDEX ix_places_city_id ON places (city_id);

CREATE TYPE device_status AS ENUM ('Offline', 'Connecting', 'Online', 'Starting', 'Recording', 'Stopping');

CREATE TABLE devices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    model VARCHAR(255) NOT NULL,
    sn VARCHAR(128) NOT NULL,
    key VARCHAR(128),
    mark_id INTEGER NOT NULL,
    protocol_id INTEGER NOT NULL,
    place_id INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    status device_status NOT NULL DEFAULT 'Offline',
    last_seen TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now (),
    CONSTRAINT pk_devices_id PRIMARY KEY (id),
    CONSTRAINT uq_devices_sn_mark UNIQUE (sn, mark_id),
    CONSTRAINT uq_devices_key UNIQUE (key),
    CONSTRAINT fk_devices_mark_id FOREIGN KEY (mark_id) REFERENCES marks (id) ON DELETE RESTRICT,
    CONSTRAINT fk_devices_place_id FOREIGN KEY (place_id) REFERENCES places (id) ON DELETE RESTRICT,
    CONSTRAINT fk_devices_protocol_id FOREIGN KEY (protocol_id) REFERENCES protocols (id) ON DELETE RESTRICT
);

CREATE INDEX ix_devices_model ON devices (model);

CREATE INDEX ix_devices_mark_id ON devices (mark_id);

CREATE INDEX ix_devices_place_id ON devices (place_id);

CREATE INDEX ix_devices_protocol_id ON devices (protocol_id);

CREATE INDEX ix_devices_status ON devices (status);

CREATE TABLE user_device_access (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL,
    device_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now (),
    CONSTRAINT pk_user_device_access_id PRIMARY KEY (id),
    CONSTRAINT uq_user_device_access_user_device UNIQUE (user_id, device_id),
    CONSTRAINT fk_user_device_access_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_device_access_device_id FOREIGN KEY (device_id) REFERENCES devices (id) ON DELETE CASCADE
);

CREATE INDEX ix_user_device_access_user_id ON user_device_access (user_id);

CREATE INDEX ix_user_device_access_device_id ON user_device_access (device_id);

CREATE TABLE records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    device_id INTEGER NOT NULL,
    procedure_id INTEGER,
    owner_id INTEGER NOT NULL,
    place_id INTEGER NOT NULL,
    title VARCHAR(255),
    description TEXT,
    start_time TIMESTAMPTZ NOT NULL DEFAULT now (),
    end_time TIMESTAMPTZ,
    seq INTEGER,
    final_status VARCHAR(32),
    stop_reason VARCHAR(64),
    output_path TEXT,
    file_size_bytes BIGINT,
    lifecycle_log TEXT,
    CONSTRAINT pk_records_id PRIMARY KEY (id),
    CONSTRAINT fk_records_device_id FOREIGN KEY (device_id) REFERENCES devices (id) ON DELETE CASCADE,
    CONSTRAINT fk_records_procedure_id FOREIGN KEY (procedure_id) REFERENCES procedures (id) ON DELETE SET NULL,
    CONSTRAINT fk_records_owner_id FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_records_place_id FOREIGN KEY (place_id) REFERENCES places (id) ON DELETE RESTRICT
);

CREATE INDEX ix_records_owner_id ON records (owner_id);

CREATE INDEX ix_records_device_id ON records (device_id);

CREATE INDEX ix_records_place_id ON records (place_id);

CREATE INDEX ix_records_start_time ON records (start_time);

COMMIT;